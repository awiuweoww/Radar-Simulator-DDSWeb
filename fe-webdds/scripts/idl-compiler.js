/**
 * UNIVERSAL OMG IDL to TypeScript Compiler
 * -----------------------------------------
 * Dirancang khusus untuk ekosistem OpenDDS/DDS-WEB.
 * Mendukung: Struct, Enum, Module, Sequence, Typedef, dan Anotasi (@).
 */

const fs = require('fs');
const path = require('path');

const TYPE_MAP = {
    'long': { ts: 'number', read: 'reader.readInt32()' },
    'unsigned long': { ts: 'number', read: 'reader.readUint32()' },
    'long long': { ts: 'number', read: 'Number(reader.readInt64())' },
    'short': { ts: 'number', read: 'reader.readInt16()' },
    'double': { ts: 'number', read: 'reader.readFloat64()' },
    'float': { ts: 'number', read: 'reader.readFloat32()' },
    'octet': { ts: 'number', read: 'reader.readUint8()' },
    'char': { ts: 'string', read: 'String.fromCharCode(reader.readUint8())' },
    'string': { ts: 'string', read: 'reader.readString()' },
    'boolean': { ts: 'boolean', read: 'reader.readBoolean()' }
};

class IDLCompiler {
    constructor() {
        this.typedefs = {};
        this.enums = {};
    }

    cleanSource(source) {
        // Hapus Komentar
        source = source.replace(/\/\/.*$/gm, '');
        source = source.replace(/\/\*[\s\S]*?\*\//g, '');
        // Hapus Anotasi IDL (@key, @topic, @id, dll)
        source = source.replace(/@\w+(\s*\([\s\S]*?\))?/g, '');
        return source.trim();
    }

    parse(source) {
        source = this.cleanSource(source);
        const results = { modules: [], structs: [], enums: [], typedefs: [] };

        // 1. Parse Typedefs
        const tdRegex = /typedef\s+sequence<([\w\s<>]+)>\s+(\w+);/g;
        let tdMatch;
        while ((tdMatch = tdRegex.exec(source)) !== null) {
            this.typedefs[tdMatch[2]] = { type: tdMatch[1].trim(), isSequence: true };
        }

        // 2. Parse Enums
        const enumRegex = /enum\s+(\w+)\s*\{([\s\S]*?)\};/g;
        let eMatch;
        while ((eMatch = enumRegex.exec(source)) !== null) {
            const name = eMatch[1];
            const values = eMatch[2].split(',').map(v => v.trim()).filter(v => v);
            this.enums[name] = values;
            results.enums.push({ name, values });
        }

        // 3. Parse Structs
        const structRegex = /struct\s+(\w+)\s*\{([\s\S]*?)\};/g;
        let sMatch;
        while ((sMatch = structRegex.exec(source)) !== null) {
            const name = sMatch[1];
            const body = sMatch[2];
            const fields = [];
            const fieldRegex = /([\w\s<>]+)\s+(\w+);/g;
            let fMatch;
            while ((fMatch = fieldRegex.exec(body)) !== null) {
                let type = fMatch[1].trim().replace(/\s+/g, ' ');
                const fieldName = fMatch[2].trim();

                if (type.startsWith('sequence<')) {
                    const inner = type.match(/sequence<([\w\s<>]+)>/)[1].trim();
                    fields.push({ name: fieldName, type: inner, isSequence: true });
                } else if (this.typedefs[type]) {
                    fields.push({ name: fieldName, type: this.typedefs[type].type, isSequence: this.typedefs[type].isSequence });
                } else {
                    fields.push({ name: fieldName, type, isSequence: false });
                }
            }
            results.structs.push({ name, fields });
        }

        return results;
    }

    generate(idlName, data) {
        let code = `/**\n * Auto-generated by Universal IDL Compiler\n * Source: ${idlName}.idl\n */\n\n`;

        // Generate Enums
        data.enums.forEach(e => {
            code += `export enum ${e.name} {\n`;
            e.values.forEach((v, i) => code += `  ${v} = ${i},\n`);
            code += `}\n\n`;
        });

        // Generate Interfaces
        data.structs.forEach(s => {
            code += `export interface ${s.name} {\n`;
            s.fields.forEach(f => {
                let tsType = TYPE_MAP[f.type]?.ts || f.type;
                if (f.isSequence) tsType += '[]';
                code += `  ${f.name}: ${tsType};\n`;
            });
            code += `}\n\n`;
        });

        return code;
    }
}

// CLI RUNNER
const args = process.argv.slice(2);
if (args.length < 2) {
    console.log("Usage: node idl-compiler.js <input_path> <output_path>");
    process.exit(1);
}

const inputPath = path.resolve(args[0]);
const outputPath = path.resolve(args[1]);

if (!fs.existsSync(inputPath)) {
    console.error("Input file not found!");
    process.exit(1);
}

const compiler = new IDLCompiler();
const rawSource = fs.readFileSync(inputPath, 'utf8');
const parsedData = compiler.parse(rawSource);
const generatedCode = compiler.generate(path.basename(inputPath, '.idl'), parsedData);

if (!fs.existsSync(path.dirname(outputPath))) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
}

fs.writeFileSync(outputPath, generatedCode);
console.log(` IDL Compiled: ${path.basename(inputPath)} -> ${path.basename(outputPath)}`);
